const EMPTY_LOCATION = {
  republic: '',
  otherrepublic: '',
  viloyat: '',
  otherviloyat: '',
  shahar_tuman: '',
  other_shahar_tuman: '',
}

/**
 * Saqlangan manzilni kaskad forma holatiga o'giradi (LocationFields uchun).
 * Ro'yxatda yo'q nom — "Boshqa" + qo'lda yozilgan matn bo'lib ochiladi.
 */
export function locationFormFromPartner(p, t) {
  const f = { ...EMPTY_LOCATION }
  if (!p?.republic) return f
  const rep = createRepublicOptions(t).find(
    (r) => r.key !== 'boshqa' && (r.value === p.republic || r.key === p.republic),
  )
  const asOther = (field, otherField, value) => {
    if (!value) return
    f[field] = 'boshqa'
    f[otherField] = value
  }
  if (!rep) {
    asOther('republic', 'otherrepublic', p.republic)
    asOther('viloyat', 'otherviloyat', p.viloyat)
    asOther('shahar_tuman', 'other_shahar_tuman', p.shahar_tuman)
    return f
  }
  f.republic = rep.key
  const vil = (createLocationData(t)[rep.key] || []).find((v) => v.value === p.viloyat)
  if (!vil) {
    asOther('viloyat', 'otherviloyat', p.viloyat)
    asOther('shahar_tuman', 'other_shahar_tuman', p.shahar_tuman)
    return f
  }
  f.viloyat = vil.value
  if (vil.tumanlar.some((x) => x.value !== 'Boshqa' && x.value === p.shahar_tuman)) {
    f.shahar_tuman = p.shahar_tuman
  } else {
    asOther('shahar_tuman', 'other_shahar_tuman', p.shahar_tuman)
  }
  return f
}

/** Kaskad forma holatidan bazaga yoziladigan manzil (doimiy o'zbekcha nomlar) */
export function locationPayload(f) {
  const rep = createRepublicOptions((s) => s).find((r) => r.key === f.republic)
  return {
    republic: f.republic === 'boshqa' ? f.otherrepublic : rep ? rep.value : f.republic || null,
    viloyat: f.viloyat === 'boshqa' ? f.otherviloyat : f.viloyat,
    shahar_tuman: f.shahar_tuman === 'boshqa' ? f.other_shahar_tuman : f.shahar_tuman,
  }
}
