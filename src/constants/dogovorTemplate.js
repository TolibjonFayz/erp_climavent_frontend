// 1 -> "один", 2 -> "два", 5 -> "пять" (jins guruhga bog'liq: ming — ayol rodi)
function tripletToWords(num, feminine) {
  const words = []
  const h = Math.floor(num / 100)
  const t = Math.floor((num % 100) / 10)
  const o = num % 10

  if (h) words.push(HUNDREDS[h])
  if (t === 1) {
    words.push(TEENS[o])
  } else {
    if (t) words.push(TENS[t])
    if (o) words.push(feminine ? ONES_F[o] : ONES_M[o])
  }
  return words.join(' ')
}

// Rus tilida son shakli: 1 -> [0], 2-4 -> [1], qolgani -> [2]
function pluralForm(num, forms) {
  const n = Math.abs(num) % 100
  const n1 = n % 10
  if (n > 10 && n < 20) return forms[2]
  if (n1 > 1 && n1 < 5) return forms[1]
  if (n1 === 1) return forms[0]
  return forms[2]
}

