// 1189776 -> "один миллион сто восемьдесят девять тысяч семьсот семьдесят шесть"
export function numberToRussianWords(value) {
  const num = Math.floor(Math.abs(Number(value) || 0))
  if (num === 0) return 'ноль'

  const triplets = []
  let rest = num
  while (rest > 0) {
    triplets.push(rest % 1000)
    rest = Math.floor(rest / 1000)
  }

  const parts = []
  for (let i = triplets.length - 1; i >= 0; i--) {
    const t = triplets[i]
    if (!t) continue
    const scale = SCALES[i] || SCALES[SCALES.length - 1]
    parts.push(tripletToWords(t, scale.feminine))
    if (i > 0) parts.push(pluralForm(t, scale.forms))
  }
  return parts.filter(Boolean).join(' ')
}

// "1 189 776,00 сум (один миллион ... сум 00 тийин)"
export function sumInWords(value) {
  const num = Number(value) || 0
  const whole = Math.floor(Math.abs(num))
  const coins = Math.round((Math.abs(num) - whole) * 100)
  const words = numberToRussianWords(whole)
  const sumWord = pluralForm(whole, ['сум', 'сума', 'сум'])
  return `${words} ${sumWord} ${String(coins).padStart(2, '0')} тийин`
}

